               )

  tmplNoOp = (False, 0, unpack minBound)
  testInput = unzip $ replicate d30 (tmplNoOp, False) ++
                      -- Wait for enable/reset
                      zipWith (\t a -> ((True, a, t), False)) tmpls (iterateI (+1) 0) ++
                      -- Write templates
                      -- replicate (SNat @(HeapSize `Div` 2)) (tmplNoOp, False) ++
