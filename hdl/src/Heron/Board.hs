simDropCycles :: Int
simDropCycles = 2 + (heapSize `div` 2)
  where
    heapSize = snatToNum (SNat @HeapSize)

simInputs :: TS.Prog -> [Pure PEIn]
simInputs p = L.concat
  [ L.zipWith (\a t -> defIn { peCode = RamWrite a t }) [0..] prog
  -- ^ Write each template
  , L.replicate (heapSize `div` 2 + 1 - L.length prog) defIn
  -- ^ Pause until GC has initialised
  , [defIn{ peGo = Just initAddr }]
  -- ^ Start reduction
  , L.repeat defIn
  -- ^ Wait
  ]
  where
    (initAddr, prog) = encProg p
    defIn :: Pure PEIn
    defIn = PEIn
      { peGo = Nothing
      , peCode = RamNoOp
      , peGcThreshold = defGcThreshold
      }
    heapSize = snatToNum (SNat @HeapSize)

simReport :: (debug -> String) -> [(Pure PEOut, debug)] -> IO (Int, CPUStats, Atom)
simReport showState simOut = do
  writeFile "/tmp/heron_sim.log" ""
  doneAt <- checkSamples $ L.zip [0::Integer ..] simOut
  case doneAt of
    Nothing  -> do
      error "Core still running... Aborting."
    Just idx -> do putStrLn $ L.concat ["Finished after ", show (idx-1), " cycles: "]
                   let final = fst $ simOut L.!! idx
                   let ans   = fromJust $ _peResult final
                   pure (idx - 1, _peStats final, ans)
  where
    checkSamples [] = pure Nothing
    checkSamples ((i,s):ss) = do
      appendFile "/tmp/heron_sim.log" ("Cycle " L.++ show i L.++ "===================")
      appendFile "/tmp/heron_sim.log" (showState $ snd s)
      if isJust . _peResult $ fst s
        then pure . Just $ fromIntegral i
        else checkSamples ss

simDUT
  :: forall dom debug
   . (KnownDomain dom, NFDataX debug)
  => Int
  -- ^ Bound on cycle count before termination (pass `maxBound` for maximumg)
  -> (Signals dom PEIn -> (Signals dom PEOut, Signal dom debug))
  -- ^ Design under test
  -> TS.Prog
  -- ^ Input program as F-lite templates
  -> IO [(Pure PEOut, debug)]
  -- ^ Output samples
simDUT limit dut p =
  let inps = unbundle . fromList $ simInputs p
      hw   = bundle $ first bundle $ dut inps
  in pure (L.take limit $
           L.drop simDropCycles $
           sample hw)

-- | Simulate `heronPE` at a Haskell-level
sim :: Int
    -- ^ Bound on cycle count before termination (pass `maxBound` for maximum)
    -> TS.Prog
    -- ^ Input program as F-lite templates
    -> IO (Int, CPUStats, Atom)
    -- ^ (Simulated cycle count, stats, return value)
sim limit p = simDUT limit dut p >>= simReport showPEState
  where dut = exposeClockResetEnable heronPE
                systemClockGen systemResetGen enableGen

  -- Report results

showPEState :: DebugState -> String
showPEState (is, os, gis, gos) = L.unlines
  [ "Stk top   : " L.++ showX (read (vStkIn is))
  , "Heap Ctrls: " L.++ showX  (_heapOut os)
  , "Result    : " L.++ showX (snd $ _result os)
  , "Stats     : " L.++ showX (fst $ _result os)
  , "AStk top  : " L.++ showX (read (aStkIn is))
  , "Outs      : " L.++ showX os
  , "Ins       : " L.++ showX is
  , "GC Ins    : " L.++ showX gis
  , "GC Outs   : " L.++ showX gos
  ]

defGcThreshold :: HeapAddr
defGcThreshold = perc d47
  where
    perc x = snatToNum $
             divSNat (mulSNat x (SNat @(HeapSize `Div` 4)))
                     d100

-- | Simulate `topEntity` at a verilog-level. Uses Clash's `outputVerifier'` to
-- produce a verilog testbench. Assertion errors will be thrown if answer is
-- wrong, too early, or too late.
--
-- For now, this is specialised to only one benchmark using Template Haskell.
testBench :: Signal DomIn Bool
testBench = done
 where
  -- Use Template Haskell to run C emulator and return benchmark's
  -- expected cycles (as type-level Nat), expected return atom,
  -- and it's compiled templates (as a Vec)
  (expCycles, expAtom, tmpls)
            = $( do prog <- runIO $ getProjectFile "tests/benchmarks/adjoxo.fl" >>= compileBenchmark
                    let code = snd (encProg prog)
                    tmplsVec <- listToVecTH code
                    (emuRet, emuCycles) <- runIO (runEmulator prog)
                    emuRetAtom <- [| PrimInt emuRet |]
                    emuCyclesS <- promoteIntTH emuCycles
                    let tup = TupE [Just emuCyclesS, Just emuRetAtom, Just tmplsVec]
                    return tup
               )

  tmplNoOp = (False, 0, unpack minBound)
  testInput = unzip $ replicate d30 (tmplNoOp, False) ++
                      -- Wait for enable/reset
                      zipWith (\t a -> ((True, a, t), False)) tmpls (iterateI (+1) 0) ++
                      -- Write templates
                      -- replicate (SNat @(HeapSize `Div` 2)) (tmplNoOp, False) ++
                      -- Wait for GC memory to initialise
                      singleton (tmplNoOp, True) ++
                      singleton (tmplNoOp, False)

  (tmplWe, tmplAddr, tmplData)
     = unbundle $ stimuliGenerator clkIn rstIn (fst testInput)
  tmplBits = fmap pack tmplData
  go = stimuliGenerator clkIn rstIn (snd testInput)
  gcThres = pure defGcThreshold

  done = withClockResetEnable clkIn rstIn enIn assertReturn expCycles expAtom .
         unbundle . topEntity clkIn rstIn enIn $ bundle (tmplWe, tmplAddr, tmplBits, go, gcThres)

  enIn           = enableGen  @DomIn
  clkIn          = tbClockGen @DomIn (fmap not done)
  rstIn          = resetGen   @DomIn

assertReturn
  :: HiddenClockResetEnable dom
  => SNat n
  -> Atom
  -> (Signal dom Atom, Signal dom CPUStats, Signal dom Bool)
  -> Signal dom Bool
assertReturn lim ans (ret, s, vld) =
  TB.assert "FAIL: BAD RETURN VALUE"
    (pure ans .==. ret)
    end
    (delay False end)
  where
    muts = _mutCycles <$> s
    -- Finishing correctly only counts when we report the expected mutator
    -- cycles too
    finished = vld .&&. muts .==. pure (snatToNum lim)
    -- Timeout after initialisation time + twice the expected mutator cycles.
    timeOut = riseEvery $ addSNat (SNat @(HeapSize `Div` 2)) $
                          mulSNat d2 lim
    end = timeOut .||. finished
