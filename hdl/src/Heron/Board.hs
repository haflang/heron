type HeronIn = Signal DomIn
  ( "codeWE"   ::: Bool
  -- ^ Template memeory write enable
  , "codeAddr" ::: TemplAddr
  -- ^ Template memeory address
  , "codeData" ::: (BitVector (BitSize Template))
  -- ^ Template memeory data
  , "go"       ::: Bool
  -- ^ Start signal
  , "gcThres"  ::: HeapAddr
  )

type HeronOut = Signal DomIn
  ("ret"    ::: Atom
  ,"stats"  ::: CPUStats
  ,"retVld" ::: Bool
  )

-- | The main synthesisable system with explicit clock, resets, enables, and
-- port names.
topEntity
  :: "clk" ::: Clock DomIn
  -- ^ Input clock
  -> "rst" ::: Reset DomIn
  -- ^ Reset
  -> "en"  ::: Enable DomIn
  -- ^ Enable
  -> HeronIn
  -> HeronOut
  -- ^ Return result atom
topEntity clkIn rstIn enIn ins = reg defOut $ bundle
  ( fromMaybe (unpack 0) <$> _peResult peOut
  , _peStats peOut
  , isJust <$> _peResult peOut
  )
  where
    (cWe, cAddr, cData, go, gcThres) = unbundle $ reg defIns ins
    defIns = (False, 0, unpack 0, False, 0)
    reg :: NFDataX a => a -> Signal DomIn a -> Signal DomIn a
    reg d x = withClockResetEnable @DomIn clkIn rstIn enIn $ register d x

    defOut = (unpack 0 :: Atom, CPUStats 0 0 0 0, False)

    -- Register inputs
    cWe'     = reg False cWe
    cAddr'   = reg 0 cAddr
    cData'   = reg 0 cData
    go'      = withClockResetEnable @DomIn clkIn rstIn enIn (isRising False) $ reg False go
    gcThres' = reg 0 gcThres

    -- Transform to a `PEIn` record
    peIn = PEIn
      { peGo = mux go' (pure $ Just 0) (pure Nothing)
      , peCode = mux cWe' (RamWrite <$> cAddr' <*> fmap unpack cData')
                          (pure RamNoOp)
      , peGcThreshold = gcThres'
      }

    (peOut, _) = withClockResetEnable @DomIn clkIn rstIn enIn $
                   heronPE @DomIn peIn

