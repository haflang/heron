data PortRx = PortRx
  { prxRead       :: Maybe ComMsg
  , prxWriteReady :: Bool
  , prxWorkload   :: Workload
  }
  deriving (Generic, NFDataX, Show, ShowX, BitPack, AutoReg)
data PortTx = PortTx
  { ptxWritePush :: Maybe ComMsg
  , ptxReadPop   :: Bool
  , ptxWorkload  :: Workload
  }
  deriving (Generic, NFDataX, Show, ShowX, BitPack, AutoReg)

declareBareB [d|
  data PEIn = PEIn
    { peGo :: Maybe TemplAddr
    -- ^ Signal to start evaluation at given template address
    , peRelease :: Bool
    -- ^ Signal to other PEs that evaluation can begin
    , peCode :: RamOp RomSize Template
    -- ^ Interface into code memory
    , peGcThreshold :: HeapAddr
    -- ^ GC triggering threshold
    , pePortsRx :: Vec 4 PortRx
    -- ^ Received port signals
    , peId :: CoreId
    } |]
deriving instance Generic (Pure PEIn)
deriving instance NFDataX (Pure PEIn)
deriving instance Show    (Pure PEIn)
deriving instance ShowX   (Pure PEIn)

